"""Build the OrcaSlicer plugin as a pure-Python wheel: dist/u1control_any.whl.

Layout inside the wheel: u1control/__init__.py (plugin.py), one module per helper, and _assets.py
(the HTML pages and SVG icon as string constants). The sources keep plain imports (`import u1`) so
they run and test in place; the build rewrites them to package-relative form in the wheel copies.
Nothing is executed or compiled at load time; the wheel is plain importable source. Zip timestamps
are fixed so equal sources give equal bytes.
"""

import ast
import argparse
import base64
import hashlib
import json
import re
import tomllib
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "u1control"
MODULES = ("moonraker", "u1", "gcode", "extended", "spoolman", "settings", "spooler_bridge", "service")  # dependency order
ASSETS = {"APP_HTML": "app.html", "SETUP_HTML": "setup.html", "ICON_SVG": "icon.svg"}
ICON_DIRS = {"icon": "icons", "toolhead": "toolheads"}   # ui/<dir>/<name>.svg -> key "<prefix>/<name>"; spot-*.svg -> "spot/*"
PLACEHOLDER = "__ICONS__"

def clean_svg(text, name):
    """Strip prolog/comments/ids, mark decorative, and refuse anything scriptable."""
    text = re.sub(r"<\?xml.*?\?>|<!--.*?-->|\s+id=\"[^\"]*\"", "", text, flags=re.S)
    text = re.sub(r">\s+<", "><", text.replace('role="img"', 'aria-hidden="true"')).strip()
    if re.search(r"<script|\bon\w+\s*=|javascript:", text, flags=re.I):
        raise SystemExit("%s: scriptable content in svg" % name)
    return text


def all_icons():
    ui = SRC / "ui"
    files = {"%s/%s" % (k, f.stem): f for k, d in ICON_DIRS.items() for f in sorted((ui / d).glob("*.svg"))}
    files.update({"spot/" + f.stem[5:]: f for f in sorted(ui.glob("spot-*.svg"))})
    return {k: clean_svg(f.read_text("utf-8"), k) for k, f in files.items()}


def page_html(name):
    """ui/<name> with the icon map injected; only icons the page references (plus all toolhead badges) are inlined."""
    html = (SRC / "ui" / name).read_text("utf-8")
    if PLACEHOLDER not in html:
        return html
    used = {k: v for k, v in all_icons().items() if k.startswith("toolhead/") or k in html}
    blob = json.dumps(used, separators=(",", ":")).replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
    return html.replace(PLACEHOLDER, blob)


def relative_imports(source):
    """`import X` -> `from . import X`, `from X import` -> `from .X import` for our modules."""
    names = "|".join(MODULES)
    source = re.sub(r"^(\s*)import (%s)(?: as (\w+))?\s*$" % names,
                    lambda m: "%sfrom . import %s%s" % (m[1], m[2], " as " + m[3] if m[3] else ""), source, flags=re.M)
    return re.sub(r"^(\s*)from (%s) import " % names, r"\1from .\2 import ", source, flags=re.M)


def wheel_files(project):
    """{path inside the wheel: bytes}, without the dist-info."""
    version = project["version"]
    plugin = (SRC / "plugin.py").read_text("utf-8")
    if plugin.count('VERSION = "0.0.0-dev"') != 1:
        raise SystemExit("plugin.py must contain exactly one VERSION placeholder")
    plugin = plugin.replace('VERSION = "0.0.0-dev"', "VERSION = %r" % version)
    sources = {"__init__": plugin, **{m: (SRC / (m + ".py")).read_text("utf-8") for m in MODULES}}
    assets = "".join("%s = %r\n" % (const, page_html(name)) for const, name in ASSETS.items())
    sources["_assets"] = "# Generated by scripts/build.py from src/u1control/ui.\n" + assets
    files = {}
    for name, text in sources.items():
        text = relative_imports(text) if name != "_assets" else text
        ast.parse(text, name + ".py")   # syntax check only
        files["u1control/%s.py" % name] = text.encode("utf-8")
    return files


def dist_info(project, files):
    di = "%s-%s.dist-info/" % (project["name"], project["version"])
    meta = {
        di + "METADATA": "\n".join([
            "Metadata-Version: 2.1",
            "Name: " + project["name"],
            "Version: " + project["version"],
            "Summary: " + project["description"],
            "Author: " + project["authors"][0]["name"],
            "License: " + project["license"],
            "Requires-Python: " + project["requires-python"],
            "",
        ]),
        di + "WHEEL": "Wheel-Version: 1.0\nGenerator: u1control scripts/build.py\nRoot-Is-Purelib: true\nTag: py3-none-any\n",
        di + "top_level.txt": "u1control\n",
    }
    meta = {k: v.encode("utf-8") for k, v in meta.items()}
    record = []
    for path, data in {**files, **meta}.items():
        digest = base64.urlsafe_b64encode(hashlib.sha256(data).digest()).rstrip(b"=").decode()
        record.append("%s,sha256=%s,%d" % (path, digest, len(data)))
    record.append(di + "RECORD,,")
    meta[di + "RECORD"] = ("\n".join(record) + "\n").encode("utf-8")
    return meta


def build(out_dir=ROOT / "dist", release_tag=None):
    project = tomllib.loads((ROOT / "pyproject.toml").read_text("utf-8"))["project"]
    if release_tag is not None and release_tag.lstrip("v") != project["version"]:
        raise SystemExit("tag %s does not match version %s" % (release_tag, project["version"]))
    files = wheel_files(project)
    files.update(dist_info(project, files))
    out_dir.mkdir(parents=True, exist_ok=True)
    artifact = out_dir / "u1control_any.whl"
    with zipfile.ZipFile(artifact, "w", zipfile.ZIP_DEFLATED) as z:
        for path, data in files.items():
            info = zipfile.ZipInfo(path, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, data)
    digest = hashlib.sha256(artifact.read_bytes()).hexdigest()
    (out_dir / "SHA256SUMS").write_text("%s  %s\n" % (digest, artifact.name), "utf-8")
    return artifact


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--release-tag")
    print(build(release_tag=parser.parse_args().release_tag))
