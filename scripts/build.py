"""Build the single-file OrcaSlicer plugin: dist/u1control_any.py.

Orca accepts one .py per plugin, so the helper modules are embedded as source strings and
registered in sys.modules under prefixed names (u1control_<name>) before plugin.py runs. The
sources keep their plain imports; the build rewrites them, so a generic name like `settings`
or `service` never lands in the shared sys.modules.
"""

import argparse
import hashlib
import json
import re
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "u1control"
MODULES = ("moonraker", "u1", "gcode", "extended", "spoolman", "settings", "spooler_bridge", "service")  # dependency order
PREFIX = "u1control_"
ASSETS = {"APP_HTML": "app.html", "SETUP_HTML": "setup.html", "ICON_SVG": "icon.svg"}
ICON_DIRS = {"icon": "icons", "toolhead": "toolheads"}   # ui/<dir>/<name>.svg -> key "<prefix>/<name>"; spot-*.svg -> "spot/*"
PLACEHOLDER = "__ICONS__"

LOADER = '''
import sys as _sys
import types as _types


def _u1control_install(name, source):
    module = _types.ModuleType(name)
    module.__file__ = __file__
    exec(compile(source, "u1control/%s.py" % name, "exec"), module.__dict__)
    _sys.modules[name] = module


for _name, _source in _U1CONTROL_SOURCES:
    _u1control_install(_name, _source)
'''


def clean_svg(text, name):
    """Strip prolog/comments/ids, mark decorative, and refuse anything scriptable."""
    text = re.sub(r"<\?xml.*?\?>|<!--.*?-->|\s+id=\"[^\"]*\"", "", text, flags=re.S)
    text = re.sub(r">\s+<", "><", text.replace('role="img"', 'aria-hidden="true"')).strip()
    if re.search(r"<script|\bon\w+\s*=|javascript:", text, flags=re.I):
        raise SystemExit("%s: scriptable content in svg" % name)
    return text


def all_icons():
    ui = SRC / "ui"
    files = {"%s/%s" % (k, f.stem): f for k, d in ICON_DIRS.items() for f in sorted((ui / d).glob("*.svg"))}
    files.update({"spot/" + f.stem[5:]: f for f in sorted(ui.glob("spot-*.svg"))})
    return {k: clean_svg(f.read_text("utf-8"), k) for k, f in files.items()}


def page_html(name):
    """ui/<name> with the icon map injected; only icons the page references (plus all toolhead badges) are inlined."""
    html = (SRC / "ui" / name).read_text("utf-8")
    if PLACEHOLDER not in html:
        return html
    used = {k: v for k, v in all_icons().items() if k.startswith("toolhead/") or k in html}
    blob = json.dumps(used, separators=(",", ":")).replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
    return html.replace(PLACEHOLDER, blob)


def prefix_imports(source):
    """`import X` -> `import u1control_X as X`, `from X import` -> `from u1control_X import` for our modules."""
    names = "|".join(MODULES)
    source = re.sub(r"^(\s*)import (%s)\s*$" % names, r"\1import %s\2 as \2" % PREFIX, source, flags=re.M)
    source = re.sub(r"^(\s*)import (%s) as (\w+)\s*$" % names, r"\1import %s\2 as \3" % PREFIX, source, flags=re.M)
    return re.sub(r"^(\s*)from (%s) import " % names, r"\1from %s\2 import " % PREFIX, source, flags=re.M)


def build(out_dir=ROOT / "dist", release_tag=None):
    project = tomllib.loads((ROOT / "pyproject.toml").read_text("utf-8"))["project"]
    version = project["version"]
    if release_tag is not None and release_tag.lstrip("v") != version:
        raise SystemExit("tag %s does not match version %s" % (release_tag, version))
    plugin = (SRC / "plugin.py").read_text("utf-8")
    replacements = {'VERSION = "0.0.0-dev"': "VERSION = %r" % version}
    for const, name in ASSETS.items():
        replacements["%s = None" % const] = "%s = %r" % (const, page_html(name))
    for old, new in replacements.items():
        if plugin.count(old) != 1:
            raise SystemExit("plugin.py must contain exactly one %r" % old)
        plugin = plugin.replace(old, new, 1)
    plugin = prefix_imports(plugin)
    sources = [(PREFIX + m, prefix_imports((SRC / (m + ".py")).read_text("utf-8"))) for m in MODULES]
    header = "\n".join([
        "# /// script",
        "# requires-python = " + json.dumps(project["requires-python"]),
        "# dependencies = []",
        "#",
        "# [tool.orcaslicer.plugin]",
        "# name = " + json.dumps(project["name"]),
        "# description = " + json.dumps(project["description"]),
        "# author = " + json.dumps(project["authors"][0]["name"]),
        "# version = " + json.dumps(version),
        "# ///",
        "# Generated by scripts/build.py from src/u1control. License: GPL-3.0-only.",
        "",
    ])
    text = header + "\n_U1CONTROL_SOURCES = %r\n" % (sources,) + LOADER + "\n" + plugin
    compile(text, "u1control_any.py", "exec")
    out_dir.mkdir(parents=True, exist_ok=True)
    artifact = out_dir / "u1control_any.py"
    artifact.write_text(text, "utf-8")
    digest = hashlib.sha256(artifact.read_bytes()).hexdigest()
    (out_dir / "SHA256SUMS").write_text("%s  %s\n" % (digest, artifact.name), "utf-8")
    return artifact


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--release-tag")
    print(build(release_tag=parser.parse_args().release_tag))
