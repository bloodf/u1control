class GcodeTests(unittest.TestCase):
    def test_process_is_idempotent(self):
        lines = SAMPLE.split("\n")
        cfg = gcode.settings(lines)
        self.assertTrue(gcode.is_u1(cfg))
        heads = u1.describe_toolheads(fakes.task_config())
        once, mode = gcode.process(lines, cfg, {}, {0: 0, 1: 3}, heads, "1")
        twice, _ = gcode.process(once, gcode.settings(once), {}, {0: 0, 1: 3}, heads, "1")
        self.assertEqual(once, twice)
        text = "\n".join(once)
        self.assertEqual(mode, "strong")
        self.assertIn(u1.PURIFIER["strong"], text)
        self.assertIn("WAIT_CHAMBER_TEMP TIMEOUT=180", text)
        self.assertIn("\nBED_MESH_CALIBRATE PROBE_COUNT=11,11\n", text)
        self.assertIn("TOTAL_LAYER=99 ", text)  # print-by-object: the layer count is left alone
        self.assertIn("\nG90\nG1 Z2.4 F600\n", text)
        self.assertNotIn("G91\nG1 Z2.4", text)
        self.assertIn("; filament_colour = #FF0000;#000000", text)
        self.assertEqual(text.count("M107 ; u1control: fan off"), 2)  # before G28 Z and BED_MESH

    def test_existing_purifier_untouched(self):
        lines = SAMPLE.replace("PRINT_START", "PRINT_START\nSET_PURIFIER_MODE MODE=3").split("\n")
        out, _ = gcode.process(lines, gcode.settings(lines), {"purifier": "weak"})
        self.assertEqual(sum(1 for l in out if l.startswith("SET_PURIFIER_MODE")), 1)

    def test_filaments_and_thumbnail(self):
        lines = SAMPLE.split("\n")
        f = gcode.filaments(lines, gcode.settings(lines))
        self.assertEqual([(x["index"], x["type"], x["weight"]) for x in f], [(0, "PLA", 3.5), (1, "PETG", 1.2)])
        self.assertEqual(gcode.thumbnail(lines), "iVBORw0KGgo=")

    def test_by_object_fallback_uses_max_height(self):
        lines = ["; print_sequence by object", "; max_print_height 270.05", "; Change Tool0 -> Tool1 (layer 1)",
                 "G91", "G1 Z1.5 F600", "G90"]
        self.assertIn("G1 Z270.05 F600", gcode.by_object_toolchange_lift(lines))

    def test_by_layer_lift_untouched(self):
        lines = ["; print_sequence by layer", "G91", "G1 Z1.5 F600", "G90"]
        self.assertEqual(gcode.by_object_toolchange_lift(lines), lines)


class SpoolmanMatchTests(unittest.TestCase):
    def test_best_spool(self):
        spools = [sm.spool_view({"id": 1, "filament": {"material": "PLA", "color_hex": "FF0000", "vendor": {"name": "X"}}}),
                  sm.spool_view({"id": 2, "filament": {"material": "PETG", "color_hex": "FF0000"}})]
        head = {"type": "PLA", "colour": "#F01010", "vendor": "X"}
        self.assertEqual(sm.best_spool(head, spools)["id"], 1)
        self.assertIsNone(sm.best_spool({"type": "ABS", "colour": "#FF0000"}, spools))
        self.assertIsNone(sm.best_spool({"type": "PLA", "colour": "#00FF00"}, spools))

    def test_locations(self):
        spools = [{"id": 4, "location": "U1 T2"}, {"id": 5, "location": "shelf"}]
        self.assertEqual(sm.bindings_from_locations(spools, "U1"), {1: 4})

    def test_locations_follow_spoolers_rule(self):
        spools = [
            {"id": 1, "location": "Snapmaker U1 T1", "last_used": "2026-11-01T00:00:00Z"},
            {"id": 2, "location": "  snapmaker  u1 t1 ", "last_used": "2026-11-09T00:00:00Z"},  # used last: wins
            {"id": 3, "location": "U1 T2"},                                   # the older form
            {"id": 4, "location": "Snapmaker U1 T3", "archived": True},       # archived never binds
            {"id": 5, "location": "Workshop U1 T4", "last_used": "2026-11-09T00:00:00Z"},
            {"id": 6, "location": "Snapmaker U1 T4", "last_used": "2026-01-01T00:00:00Z"},  # exact name beats it
            {"id": 7, "location": "Shelf T1"}, {"id": 8, "location": "Snapmaker U1 T10"},
        ]
        self.assertEqual(sm.bindings_from_locations(spools, "Snapmaker U1"), {0: 2, 1: 3, 3: 6})

    def test_spool_view_keeps_what_binding_needs(self):
        view = sm.spool_view({"id": 1, "location": "U1 T1", "last_used": "2026-11-09T00:00:00Z", "archived": True})
        self.assertEqual((view["last_used"], view["archived"]), ("2026-11-09T00:00:00Z", True))


class PrinterTests(unittest.TestCase):
    def setUp(self):
        self.fake = fakes.FakePrinter(spoolman=False)
        self.addCleanup(self.fake.close)
        self.mr = Moonraker(self.fake.host)

    def test_client(self):
        self.assertEqual(self.mr.info()["software_version"], "2.0.0.205")
        status = self.mr.query(u1.STATUS_OBJECTS)
        self.assertEqual(u1.summarize(status)["heads"][1]["type"], "PETG")
        self.mr.gcode("M105")
        self.assertEqual(self.fake.scripts, ["M105"])
        self.mr.delete_file("gcodes/sub dir/a.gcode")
        self.assertEqual(self.fake.deleted, ["/server/files/gcodes/sub dir/a.gcode"])

    def test_http_error_message(self):
        with self.assertRaises(PrinterError) as e:
            self.mr.request("GET", "/nope")
        self.assertIn("not found", str(e.exception))

    def test_unreachable(self):
        with self.assertRaises(PrinterError):
            Moonraker("127.0.0.1:1", timeout=1).info()

    def _service(self, **target):
        published = []
        svc = Service(published.append, log=lambda m: None)
        self.addCleanup(svc.close)
        svc.set_target(Target(self.fake.host, **target))
        return svc, published

    def _call(self, svc, published, cmd, **args):
        rid = len(published) + 1000
        svc.submit(rid, cmd, args)
        self.assertTrue(wait_for(lambda: any(m.get("id") == rid for m in published)))
        reply = next(m for m in published if m.get("id") == rid)
        if "error" in reply:
            raise RuntimeError(reply["error"])
        return reply["result"]

    def test_service_files_and_firmware(self):
        svc, pub = self._service()
        self.assertEqual(self._call(svc, pub, "connect")["firmware"]["kind"], "stock")
        files = self._call(svc, pub, "files", path="gcodes")
        self.assertEqual([f["name"] for f in files["files"]], ["b.gcode", "a.gcode"])
        self.assertEqual([d["name"] for d in files["dirs"]], ["sub"])
        self._call(svc, pub, "delete", path="gcodes/a.gcode")
        self.assertIn("/server/files/gcodes/a.gcode", self.fake.deleted)
        with self.assertRaises(RuntimeError):
            self._call(svc, pub, "delete", path="gcodes")
        self._call(svc, pub, "power_loss", action="discard")
        self.assertEqual(self.fake.scripts[-1], "SDCARD_PRINT_PL_CLEAR_ENV")
        self._call(svc, pub, "emergency_stop")
        self.assertEqual(self.fake.scripts[-1], "M112")
        with self.assertRaises(RuntimeError):
            self._call(svc, pub, "ext_settings")  # stock firmware
        self._call(svc, pub, "print_file", path="gcodes/b.gcode")
        self.assertEqual(self.fake.started, ["b.gcode"])

    def test_extended_config(self):
        self.fake.extended, self.fake.version = True, "2.0.0-paxx12-24"
        svc, pub = self._service()
        self.assertEqual(self._call(svc, pub, "connect")["firmware"]["kind"], "extended")
        self.assertEqual(self._call(svc, pub, "ext_settings")["settings"][0]["id"], "ssh")
        self.assertTrue(self._call(svc, pub, "ext_set", setting_id="ssh", value="true")["ok"])
        with self.assertRaises(RuntimeError):
            self._call(svc, pub, "ext_set", setting_id="../x", value="1")

    def test_spoolman_bind_follow_and_usage(self):
        svc, pub = self._service(spoolman_url="http://" + self.fake.host)
        self._call(svc, pub, "connect")
        spools = self._call(svc, pub, "spools")
        self.assertEqual(len(spools["spools"]), 3)
        self._call(svc, pub, "bind_spool", head=3, spool_id=7)
        self.assertIn((7, {"location": "Snapmaker U1 T4"}), self.fake.patches)
        self.assertTrue(self.fake.scripts[-1].startswith("SET_PRINT_FILAMENT_CONFIG CONFIG_EXTRUDER=3 VENDOR=Generic "
                                                         "FILAMENT_TYPE=PLA FILAMENT_SUBTYPE=Matte_Black FILAMENT_COLOR_RGBA=111111FF"))
        # head 0's colour changes on the printer -> closest PLA spool (#9 red) gets bound automatically
        svc.touch()
        self.assertTrue(wait_for(lambda: any(m.get("type") == "status" for m in pub)))
        self.fake.task["filament_official"][0] = False   # an official / tagged head is never rebound automatically
        self.fake.task["filament_color_rgba"][0] = "EE1111FF"
        self.assertTrue(wait_for(lambda: svc.bindings.get(0) == 9, 6))
        self.assertIn((9, {"location": "Snapmaker U1 T1"}), self.fake.patches)
        # print finishes -> grams from the job u1control sent are deducted per toolhead
        svc.remember_job("a.gcode", {0: 0, 1: 3}, [{"index": 0, "weight": 3.5}, {"index": 1, "weight": 1.2}])
        self.fake.state = "printing"
        svc.touch()
        self.assertTrue(wait_for(lambda: svc.last_state == "printing", 6))
        self.fake.state = "complete"
        svc.touch()
        self.assertTrue(wait_for(lambda: len(self.fake.uses) == 2, 6))
        self.assertIn((9, {"use_weight": 3.5}), self.fake.uses)
        self.assertIn((7, {"use_weight": 1.2}), self.fake.uses)


    def test_rfid_change_published_once(self):
        svc, pub = self._service()
        svc.touch()
        self.assertTrue(wait_for(lambda: svc.last_view is not None))
        self.assertEqual([m for m in pub if m.get("type") == "rfid"], [])  # first status: no event
        self.fake.tags[1] = {"VENDOR": "Polymaker", "MAIN_TYPE": "PETG", "SUB_TYPE": "Basic", "RGB_1": 0x00FF00, "COLOR_NUMS": 1}
        end = time.time() + 7
        while time.time() < end and not any(m.get("type") == "rfid" for m in pub):
            svc.touch()
            time.sleep(0.2)
        events = [m for m in pub if m.get("type") == "rfid"]
        self.assertEqual(len(events), 1)
        self.assertEqual(events[0]["heads"], [1])
        self.assertEqual(events[0]["tags"][1]["vendor"], "Polymaker")
        time.sleep(2.5)
        svc.touch()
        self.assertEqual(len([m for m in pub if m.get("type") == "rfid"]), 1)


class PluginTests(unittest.TestCase):
    """Loads the built single-file plugin against a fake orca module."""

    @classmethod
    def setUpClass(cls):
        import build
        cls.artifact = str(build.build(out_dir=__import__("pathlib").Path(tempfile.mkdtemp())))

    def load(self, answer=None, preset=None, filament_names=()):
        orca = fakes.install_orca(answer, preset, filament_names)
        ns = runpy.run_path(self.artifact)
        return orca, ns

    def setUp(self):
        self.fake = fakes.FakePrinter()
        self.addCleanup(self.fake.close)
        fd, self.path = tempfile.mkstemp(suffix=".gcode")
        os.close(fd)
        with open(self.path, "w") as f:
            f.write(SAMPLE)

    def ctx(self, host):
        return types.SimpleNamespace(step="post", gcode_path=self.path, host=host, output_name="part.gcode",
                                     config_value=lambda k: {"print_host": self.fake.host}.get(k, ""))

    def test_registers_capabilities(self):
        orca, ns = self.load()
        ns["U1Control"]().register_capabilities()
        self.assertEqual([c.__name__ for c in orca.registered],
                         ["U1ControlPage", "U1PrintSetup", "CheckConnection", "SyncHeadsToProject", "ApplyForkTuning"])

    def test_print_setup_sends_mapping(self):
        orca, ns = self.load(answer={"map": {"1": 3}, "prefs": {"bed_level": True}, "purifier": "weak"})
        cap = ns["U1PrintSetup"]()
        result = cap.execute(self.ctx("OctoPrint"))
        self.assertEqual(result.status, "success", result.message)
        script = self.fake.scripts[-1]
        self.assertIn("SET_PRINT_EXTRUDER_MAP CONFIG_EXTRUDER=1 MAP_EXTRUDER=3", script)
        self.assertIn("BED_LEVEL=1", script)
        self.assertIn("AUTO_REPLENISH_FILAMENT=1", script)  # printer's own value carried over
        with open(self.path) as f:
            text = f.read()
        self.assertIn(u1.PURIFIER["weak"], text)
        data = json.loads(orca.windows[0].html.split("const D = ", 1)[1].split(";\nconst $", 1)[0])
        self.assertEqual(data["map"], {"0": 0, "1": 1})
        self.assertTrue(ns["get_store"](cap).effective()["prefs"]["bed_level"])  # remembered

    def test_export_only_edits_file(self):
        _, ns = self.load()
        result = ns["U1PrintSetup"]().execute(self.ctx("File"))
        self.assertEqual(result.status, "success")
        self.assertEqual(self.fake.scripts, [])

    def test_busy_printer_refused(self):
        self.fake.state = "printing"
        _, ns = self.load()
        result = ns["U1PrintSetup"]().execute(self.ctx("OctoPrint"))
        self.assertEqual(result.status, "failure")
        self.assertIn("printing", result.message)

    def test_cancel(self):
        _, ns = self.load(answer={"cancelled": True})
        result = ns["U1PrintSetup"]().execute(self.ctx("OctoPrint"))
        self.assertEqual(result.status, "failure")
        self.assertIn("cancelled", result.message)
        self.assertEqual(self.fake.scripts, [])

    def test_tuning_changes(self):
        _, ns = self.load()
        changes = ns["tuning_changes"]("0.18 Standard @Snapmaker U1 (0.6 nozzle)",
                                       {"wall_generator": "arachne", "precise_outer_wall": "0", "layer_height": "0.25"})
        self.assertEqual([c[0] for c in changes], ["wall_generator", "tree_support_branch_angle_organic", "layer_height"])

    def test_pick_filament_preset(self):
        _, ns = self.load()
        names = ["Generic PLA", "Generic PLA @U1", "Generic PETG @U1", "Snapmaker PLA Matte @U1"]
        self.assertEqual(ns["pick_filament_preset"](names, {"type": "PETG", "vendor": "Generic"}), "Generic PETG @U1")
        self.assertEqual(ns["pick_filament_preset"](names, {"type": "PLA", "vendor": "Snapmaker"}), "Snapmaker PLA Matte @U1")

    def test_pick_with_tag_overrides_and_preference(self):
        _, ns = self.load()
        pick = ns["pick_filament_preset"]
        names = ["Generic PLA @U1", "Generic PLA Silk @U1", "Polymaker PLA @U1", "Snapmaker PLA Matte @U1",
                 "Snapmaker PLA SnapSpeed @U1", "Generic PLA-CF @U1", "Generic PLA @BBL X1C", "Generic PETG @U1"]
        head = {"type": "PLA", "vendor": "Generic", "sub_type": "Basic"}
        self.assertEqual(pick(names, head), "Generic PLA @U1")
        self.assertEqual(pick(names, {**head, "sub_type": "Silk"}), "Generic PLA Silk @U1")
        self.assertEqual(pick(names, {**head, "type": "PLA-CF"}), "Generic PLA-CF @U1")
        self.assertEqual(pick(names, head, {"vendor": "Snapmaker", "type": "PLA", "sub_type": "SnapSpeed"}),
                         "Snapmaker PLA SnapSpeed @U1")
        self.assertEqual(pick(names, head, {"vendor": "Polymaker", "type": "PLA"}), "Polymaker PLA @U1")  # tag vendor wins
        self.assertEqual(pick(names, head, {"manufacturer": "Polymaker", "type": "PLA"}), "Polymaker PLA @U1")
        self.assertEqual(pick(names, {"type": "ABS"}), "")
        tag = {"vendor": "Polymaker", "type": "PLA", "sku": "S1", "uid": "AABB"}
        self.assertEqual(pick(names, head, tag, {"SKU:S1": "Generic PLA Silk @U1"}), "Generic PLA Silk @U1")
        self.assertEqual(pick(names, head, tag, {"uid:aabb": "Generic PETG @U1", "SKU:S1": "Generic PLA Silk @U1"}),
                         "Generic PETG @U1")
        self.assertEqual(pick(names, head, tag, {"polymaker|pla|": "Snapmaker PLA Matte @U1"}), "Snapmaker PLA Matte @U1")
        self.assertEqual(pick(names, head, tag, {"SKU:S1": "Missing"}), "Polymaker PLA @U1")  # unknown name ignored
        self.assertEqual(pick(names, head, preference=lambda n, h, t: "Generic PETG @U1"), "Generic PETG @U1")

    def test_sync_project(self):
        orca, ns = self.load(filament_names=["Generic PETG @U1", "Polymaker PLA @U1", "Generic PLA @U1"])
