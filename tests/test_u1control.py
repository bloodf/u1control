def wait_for(pred, timeout=5):
    end = time.time() + timeout
    while time.time() < end:
        if pred():
            return True
        time.sleep(0.05)
    return False


class DomainTests(unittest.TestCase):
    def setUp(self):
        self.heads = u1.describe_toolheads(fakes.task_config())

    def test_toolheads(self):
        self.assertEqual(self.heads[0]["colour"], "#FF0000")
        self.assertTrue(self.heads[0]["official"])
        self.assertFalse(self.heads[2]["loaded"])
        self.assertEqual(self.heads[3]["sub_type"], "Matte")

    def test_auto_map_prefers_material_then_colour(self):
        fils = [{"index": 0, "type": "PETG", "colour": "#FFFFFF"}, {"index": 1, "type": "PLA", "colour": "#000000"},
                {"index": 2, "type": "PLA", "colour": "#FF1010"}]
        self.assertEqual(u1.auto_map(fils, self.heads), {0: 1, 1: 3, 2: 0})

    def test_auto_map_no_loaded_heads(self):
        heads = [dict(h, loaded=False) for h in self.heads]
        self.assertEqual(u1.auto_map([{"index": 5, "type": "PLA"}], heads), {5: 1})

    def test_warnings(self):
        fils = [{"index": 0, "type": "PLA"}]
        self.assertIn("empty", u1.mapping_warnings(fils, self.heads, {0: 2})[0])
        self.assertIn("PETG", u1.mapping_warnings(fils, self.heads, {0: 1})[0])

