"""Built wheel ships the compiled Vue page (icons from the shared foundation) and the tab icon, with no unresolved placeholders."""

import hashlib
import json
import re
import sys
import tempfile
import unittest
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import build  # noqa: E402

UI = ROOT / "src" / "u1control" / "ui"
MAX_BUILT_BYTES = 650_000   # the zipped wheel: the page deflates to ~450 kB with the photo spool (foundation 4.1.0 on)


class UiAssets(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.artifact = build.build(out_dir=Path(tempfile.mkdtemp()))
        with zipfile.ZipFile(cls.artifact) as z:
            cls.text = z.read("u1control/_assets.py").decode("utf-8")
            cls.shipped = z.read("u1control/app.html").decode("utf-8")

    def test_page_ships_as_built(self):
        """Icons come from the shared foundation, compiled into the page: nothing is injected at build time."""
        html = build.page_html("app.html")
        self.assertEqual(html, (UI / "app.html").read_text("utf-8"))
        self.assertNotIn("__ICONS__", html)
        self.assertNotIn('id="u1-icons"', html)
        self.assertEqual(self.page(), html)   # the wheel carries exactly this page
        self.assertNotIn("SETUP_HTML", self.text)   # one page serves the tab and the print setup window

    def test_committed_page_is_the_recorded_vue_build(self):
        """src/u1control/ui/app.html is generated by `npm run build` in ui/; a hand edit or a stale build fails here."""
        info = json.loads((ROOT / "ui" / "build.json").read_text("utf-8"))
        data = (UI / "app.html").read_bytes()
        self.assertEqual(hashlib.sha256(data).hexdigest(), info["sha256"])
        html = data.decode("utf-8")
        self.assertEqual(html.count("__BOOT__"), 1)
        self.assertEqual(html.count("__ICONS__"), 0)
        self.assertNotRegex(html, r"<script[^>]+src=|<link[^>]+href=\"https?:|@import\s*(?:url\(|['\"])|url\(https?:")
        self.assertNotRegex(html, r"\bnew Function\b|\beval\(")
        self.assertIn("__VUE_OPTIONS_API__", (ROOT / "ui" / "vite.config.ts").read_text("utf-8"))
        self.assertFalse((UI / "setup.html").exists(), "the legacy setup page was replaced by the Vue page")

    def test_no_local_icon_files_left(self):
        """The old per-plugin SVG icons, spot pictures and toolhead badges were replaced by the foundation's set."""
        self.assertFalse((UI / "icons").exists())
        self.assertFalse((UI / "toolheads").exists())
        self.assertEqual(sorted(p.name for p in UI.glob("spot-*.svg")), [])
        self.assertNotRegex((UI / "app.html").read_text("utf-8"), r"\b(?:icon|spot|toolhead)/(?:emergency-stop|toolheads-rfid|camera-off|t1)\b")

    def page(self):
        """The page as the wheel ships it: u1control/app.html."""
        return self.shipped

    def test_page_ships_as_a_plain_file(self):
        """The page is u1control/app.html, byte for byte the build, not a Python string: _assets.py holds the icon only."""
        self.assertEqual(self.shipped, build.page_html("app.html"))
        self.assertNotIn("APP_HTML", self.text)
        self.assertNotIn("<script", self.text)

    def test_installed_plugin_unpacks_the_page(self):
        """The wheel imported as OrcaSlicer imports it: _asset returns the exact page and the tab icon."""
        sys.path.insert(0, str(ROOT / "tests"))
        import fakes
        fakes.install_orca()
        ns = fakes.load_wheel(self.artifact)
        self.assertEqual(ns["_asset"]("app.html"), build.page_html("app.html"))
        self.assertEqual(ns["_asset"]("icon.png"), (UI / "icon.png").read_bytes())

    def test_no_unresolved_placeholders(self):
        self.assertNotIn("__ICONS__", self.page())
        self.assertNotIn("__ICONS__", build.page_html("app.html"))
        self.assertIn("__BOOT__", build.page_html("app.html"))   # filled per page by plugin.page_html

    def test_printer_photo_credit_ships(self):
        """The Dashboard's printer photo is Snapmaker's product image: NOTICE.md (its credit) is in the wheel."""
        with zipfile.ZipFile(self.artifact) as z:
            notice = [n for n in z.namelist() if n.endswith(".dist-info/licenses/NOTICE.md")]
            self.assertEqual(len(notice), 1)
            self.assertIn("Printer photo: Snapmaker product image", z.read(notice[0]).decode("utf-8"))

    def test_built_size_reasonable(self):
        size = self.artifact.stat().st_size
        print("built size: %d bytes" % size)
        self.assertLess(size, MAX_BUILT_BYTES)


if __name__ == "__main__":
    unittest.main()
